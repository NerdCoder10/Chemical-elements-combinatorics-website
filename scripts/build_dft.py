#!/usr/bin/env python3
"""Generate js/dft.js: computed (DFT) formation energies for ~65,000 compounds.

Source: JARVIS-DFT 3D dataset (NIST), OptB88vdW functional, release 2025-09-24
  https://ndownloader.figshare.com/files/64391379   (jdft_3d-9-24-2025.json.zip)
  sha256 f9e0a3309f0000d5de1ec9e49c93963109ea45e63f451103f8f6595d2eabf7f5
Citation: K. Choudhary et al., "The joint automated repository for various integrated
  simulations (JARVIS) for data-driven materials design", npj Comput. Mater. 6, 173 (2020).

For every distinct formula the polymorph with the lowest formation energy is kept. The energy
above the convex hull is then recomputed here from those formation energies (pymatgen
PhaseDiagram over each chemical system and all of its subsystems), because the "ehull" field
shipped in the dataset is not consistent with its own formation energies (e.g. it places
Al2O3 1.6 eV/atom above the hull although it is the lowest-energy Al-O compound).

Run:  pip install pymatgen && python3 scripts/build_dft.py
(downloads ~48 MB into data/cache/ on first run).
"""
import collections
import hashlib
import itertools
import multiprocessing
import json
import os
import re
import urllib.request
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
URL = 'https://ndownloader.figshare.com/files/64391379'
SHA256 = 'f9e0a3309f0000d5de1ec9e49c93963109ea45e63f451103f8f6595d2eabf7f5'
CACHE = os.path.join(ROOT, 'data', 'cache', 'jdft_3d-9-24-2025.json.zip')
OUT = os.path.join(ROOT, 'js', 'dft.js')


def fetch():
    if not os.path.exists(CACHE):
        os.makedirs(os.path.dirname(CACHE), exist_ok=True)
        print('downloading', URL)
        urllib.request.urlretrieve(URL, CACHE)
    h = hashlib.sha256(open(CACHE, 'rb').read()).hexdigest()
    if h != SHA256:
        raise SystemExit(f'checksum mismatch for {CACHE}: {h}')
    z = zipfile.ZipFile(CACHE)
    return json.load(z.open(z.namelist()[0]))


def hull_for_system(args):
    """Energy above hull for every compound whose element set is exactly `system`."""
    import warnings
    warnings.filterwarnings('ignore')  # pymatgen warns about noble gases lacking electronegativities
    from pymatgen.analysis.phase_diagram import PDEntry, PhaseDiagram
    from pymatgen.core import Composition
    system, members = args
    entries = [PDEntry(Composition(el), 0.0) for el in system]
    targets = []
    for f, fe, exact in members:
        comp = Composition(f)
        entry = PDEntry(comp, fe * comp.num_atoms)
        entries.append(entry)
        if exact:
            targets.append((f, entry))
    pd = PhaseDiagram(entries)
    return [(f, pd.get_e_above_hull(e, allow_negative=True)) for f, e in targets]


def compute_hulls(best):
    by_set = collections.defaultdict(list)
    for f, e in best.items():
        by_set[tuple(sorted(set(re.findall(r'[A-Z][a-z]?', f))))].append(f)
    jobs = []
    for system in by_set:
        members = []
        for k in range(2, len(system) + 1):
            for sub in itertools.combinations(system, k):
                for f in by_set.get(sub, ()):
                    members.append((f, best[f]['formation_energy_peratom'], sub == system))
        jobs.append((list(system), members))
    jobs.sort(key=lambda j: -len(j[1]))
    out = {}
    with multiprocessing.Pool() as pool:
        for i, res in enumerate(pool.imap_unordered(hull_for_system, jobs, chunksize=8)):
            out.update(res)
            if i % 5000 == 0:
                print(f'  hulls: {i}/{len(jobs)} systems')
    return out


def has_icsd(v):
    return isinstance(v, str) and v.strip() not in ('', 'na', 'NA', 'None')


def main():
    data = fetch()
    best = {}
    polymorphs = collections.Counter()
    known = set()
    for e in data:
        fe, eh = e['formation_energy_peratom'], e['ehull']
        if not isinstance(fe, (int, float)) or not isinstance(eh, (int, float)):
            continue
        f = e['formula']
        if len(re.findall(r'[A-Z][a-z]?', f)) < 2:
            continue  # pure elements
        polymorphs[f] += 1
        if has_icsd(e.get('icsd')):
            known.add(f)
        if f not in best or fe < best[f]['formation_energy_peratom']:
            best[f] = e

    print(f'{len(best)} formulas; computing convex hulls ...')
    ehull = compute_hulls(best)

    rows = []
    for f, e in best.items():
        gap = e['optb88vdw_bandgap']
        gap = round(gap, 2) if isinstance(gap, (int, float)) else ''
        rows.append('|'.join(str(x) for x in (
            f,
            round(e['formation_energy_peratom'], 3),
            round(max(ehull[f], 0), 3),
            e['spg_symbol'],
            gap,
            1 if f in known else 0,
            polymorphs[f],
            e['jid'].replace('JVASP-', ''),
        )))
    rows.sort()

    header = f"""/*
 * GENERATED by scripts/build_dft.py. Do not edit by hand.
 *
 * {len(rows)} compounds with DFT-computed formation energies from JARVIS-DFT (NIST),
 * OptB88vdW functional, release 2025-09-24. K. Choudhary et al., npj Comput. Mater. 6, 173 (2020).
 *
 * Energies above the convex hull were computed by scripts/build_dft.py (pymatgen PhaseDiagram).
 *
 * Row: formula | ΔHf (eV/atom) | energy above convex hull (eV/atom) | space group |
 *      band gap (eV, OptB88vdW) | 1 = structure known experimentally (ICSD) | polymorphs computed | JVASP id
 */
"""
    js = header + """(function (root) {
  const DFT_ROWS = """ + json.dumps('\n'.join(rows)) + """;
  const api = { DFT_ROWS };
  if (typeof module !== 'undefined' && module.exports) module.exports = api;
  else Object.assign(root, api);
})(this);
"""
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write(js)
    print(f'wrote {OUT}: {len(rows)} compounds, {len(js) // 1024} KB')


if __name__ == '__main__':
    main()
