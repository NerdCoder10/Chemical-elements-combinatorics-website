#!/usr/bin/env node
/*
 * Predict the outcome for every pair of the 118 elements with js/predict.js (6,903 pairs), for the
 * combinations map. Writes js/pair-predictions.js: "A-B|forms (1/0)|formula|ΔHf kJ/mol per atom|confidence".
 * Run:  node scripts/atlas/build_pair_predictions.js
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');
const Predict = require(path.join(ROOT, 'js', 'predict.js'));
const { ELEMENTS } = require(path.join(ROOT, 'js', 'elements.js'));

const rows = [];
let forms = 0;
for (let i = 0; i < ELEMENTS.length; i += 1) {
  for (let j = i + 1; j < ELEMENTS.length; j += 1) {
    const p = Predict.predictSet([ELEMENTS[i].symbol, ELEMENTS[j].symbol]);
    const best = p.products[0];
    if (p.forms) forms += 1;
    rows.push([p.syms.join('-'), p.forms ? 1 : 0, best ? best.formula : '', best ? Math.round(best.feKj) : '', p.confidence[0]].join('|'));
  }
}
const header = `/*
 * GENERATED by scripts/atlas/build_pair_predictions.js. Do not edit by hand.
 * The composition model's prediction for all ${rows.length} pairs of elements: ${forms} are predicted to form a compound.
 * Row: elements | 1 = a compound is predicted | formula | ΔHf (kJ/mol per atom) | m = model, e = extrapolated, r = rule
 */
`;
fs.writeFileSync(path.join(ROOT, 'js', 'pair-predictions.js'), `${header}var PAIR_PREDICTIONS = ${JSON.stringify(rows.join('\n'))};
if (typeof module !== 'undefined' && module.exports) module.exports = { PAIR_PREDICTIONS };
`);
console.log(`${rows.length} pairs, ${forms} predicted to form a compound`);
