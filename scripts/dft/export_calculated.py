#!/usr/bin/env python3
"""Collect the calculations in data/calculated/result_*.json into js/calculated.js for the site.
Run: python3 scripts/dft/export_calculated.py"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
rows = [json.load(open(p)) for p in sorted(glob.glob(os.path.join(ROOT, 'data', 'calculated', 'result_*.json')))]
with open(os.path.join(ROOT, 'js', 'calculated.js'), 'w') as fh:
    fh.write('/*\n * GENERATED by scripts/dft/export_calculated.py from data/calculated/result_*.json. Do not edit by hand.\n'
             ' * DFT calculations run for this site (scripts/dft/). Each entry lists its method and raw energies.\n */\n'
             f'var CALCULATED = {json.dumps(rows, indent=1)};\n'
             "if (typeof module !== 'undefined' && module.exports) module.exports = { CALCULATED };\n")
print(f'{len(rows)} calculated result(s) exported')
